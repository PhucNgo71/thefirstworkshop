// Rebuild exact-text translations after changing product specifications.
const fs=require('node:fs');
const path=require('node:path');
const {entries,context,overrides}=require('./audit-product-english.cjs');
const edits=require('./product-specifications-en.json');
const dictionary={...require('./specification-labels-en.json')};
for(const [id] of entries){
  if(!edits[id])continue;
  const source={...context.window.productDetails[id],...overrides[id],...context.window.productGalleryOverrides?.[id]};
  if(!source.specifications)throw new Error(`No source specifications for ${id}`);
  if(dictionary[source.specifications]&&dictionary[source.specifications]!==edits[id])throw new Error(`Conflicting translation for ${id}`);
  dictionary[source.specifications]=edits[id];
}
fs.writeFileSync(path.join(__dirname,'../dist/specification-translations.js'),'// Generated by scripts/build-specification-translations.cjs.\nwindow.specificationTranslations = '+JSON.stringify(dictionary,null,2)+';\n');
console.log(`Built ${Object.keys(dictionary).length} specification translations for ${Object.keys(edits).length} products.`);
